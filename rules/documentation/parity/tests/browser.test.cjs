"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),os=require("node:os"),path=require("node:path");
const {serve,capture}=require("../validation.cjs");
const {compare}=require("../comparison.cjs");
const {chromium}=require("../../../../.github/components/documentation/pages/build/starlight/node_modules/playwright");
test("actual browser detects style, geometry and interaction changes",async t=>{
    const directory=fs.mkdtempSync(path.join(os.tmpdir(),"documentation-browser-"));
    t.after(()=>fs.rmSync(directory,{recursive:true,force:true}));
    const site=path.join(directory,"site");
    fs.mkdirSync(site);
    const markup=(color,padding)=>'<style>h1{color:'+color+';padding:'+padding+'px}</style><h1>Test title</h1><details><summary>Toggle</summary>Content</details>';
    fs.writeFileSync(path.join(site,"index.html"),markup("red",4));
    const server=await serve(site,"/specimen/");
    t.after(()=>server.close());
    const browser=await chromium.launch();
    t.after(()=>browser.close());
    const scenario={viewport:{width:800,height:600},elements:[{id:"title",reference:"h1",candidate:"h1"},{id:"details",reference:"details",candidate:"details"}]};
    const url=server.url+"/specimen/";
    const reference=await capture(browser,url,scenario,"reference",path.join(directory,"ref"),server.url);
    const same=await capture(browser,url,scenario,"candidate",path.join(directory,"same"),server.url);
    assert.deepEqual(compare(reference,same,1,["title","details"]),[]);
    assert(fs.readFileSync(path.join(directory,"ref","viewport.png")).equals(fs.readFileSync(path.join(directory,"same","viewport.png"))));
    fs.writeFileSync(path.join(site,"index.html"),markup("blue",12));
    const changed=await capture(browser,url,{...scenario,actions:[{kind:"click",candidate:"summary"}]},"candidate",path.join(directory,"changed"),server.url);
    const differences=compare(reference,changed,1,["title","details"]);
    assert(differences.some(x=>x.includes("title.color")));
    assert(differences.some(x=>x.includes("title.height")));
    assert(differences.some(x=>x.includes("details.open")));
    assert(!fs.readFileSync(path.join(directory,"ref","viewport.png")).equals(fs.readFileSync(path.join(directory,"changed","viewport.png"))));
});
