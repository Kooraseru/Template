import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

// Lune stdin cannot require modules. Keep the executable adapter in generated output.
export function runLuauCheck(file, options = {}) {
  if (!file.startsWith('ci/validation/')) return spawnSync('lune', ['run', file], options);
  if (!/^ci\/validation\/(?:tests\/)?[a-z-]+\.luau$/.test(file)) throw Error('Invalid validation module path');
  const adapter = 'build/validation/invoke.luau';
  const modulePath = '../../' + file.slice(0, -5);
  fs.mkdirSync(path.dirname(adapter), { recursive: true });
  fs.writeFileSync(adapter, `-- Generated by ci/control/run-check.mjs; edit the validation module.\nrequire(${JSON.stringify(modulePath)}).Run()\n`);
  return spawnSync('lune', ['run', adapter], options);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = runLuauCheck(process.argv[2] || '', { stdio: 'inherit' });
  if (result.error) throw result.error;
  process.exitCode = result.status ?? 1;
}
